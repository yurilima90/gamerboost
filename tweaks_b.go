// rmApps monta um script que remove pacotes da Microsoft Store (usuário atual, todos e pré-instalados).
func rmApps(names ...string) Action {
	list := "'" + strings.Join(names, "','") + "'"
	return P(`$ErrorActionPreference='SilentlyContinue'; foreach($n in @(` + list + `)){ Get-AppxPackage -AllUsers -Name $n | Remove-AppxPackage -AllUsers; Get-AppxProvisionedPackage -Online | Where-Object { $_.DisplayName -like $n } | Remove-AppxProvisionedPackage -Online | Out-Null }`)
}

